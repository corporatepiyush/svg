#!/usr/bin/env python3
"""Deterministic benchmark harness for svg2img.

Runs every SVG in ``bench/cases`` (generated by ``bench/gen.py``) a few times
through the renderer and records wall time and peak RSS.  A committed baseline
(``bench/baseline.json``) stores per-case medians measured on a reference
machine; the harness compares against it and applies a regression threshold.

Design choices that keep this honest rather than decorative:

* **Machine identity is recorded, not assumed.**  ``baseline.json`` carries the
  CPU, core count and Python version it was measured on.  A different machine
  still runs the benchmark but is reported as *unbaselined* instead of being
  compared against numbers it cannot reproduce.
* **Thresholds are relative and overridable.**  The default is 1.35x slower
  than baseline (30% headroom for noise); ``--threshold`` overrides it.  RSS
  gets its own, wider threshold because allocator behaviour varies more.
* **Best-of-N, not mean-of-N.**  The minimum wall time over ``--repeat`` runs is
  the least noisy estimator on a shared machine; means hide scheduler noise.
* **Peak RSS via ``resource.getrusage``** (``ru_maxrss``), which is portable to
  macOS and Linux and needs no external ``/usr/bin/time``.
* **Never blocks a build by default.**  ``--check`` returns non-zero on a
  regression; without it the run only reports.

Usage:
    python3 bench/run.py [--bin PATH] [--repeat N] [--threshold F]
                         [--rss-threshold F] [--json FILE] [--md FILE]
                         [--update-baseline] [--check] [--filter NAME]
"""
import argparse
import json
import os
import platform
import resource
import statistics
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CASES = os.path.join(HERE, "cases")
BASELINE = os.path.join(HERE, "baseline.json")
DEFAULT_JSON = os.path.join(HERE, "results.json")

# Baseline provenance.  Bump ``version`` when the measurement protocol changes;
# a mismatched version is treated as "no baseline" rather than compared.
BASELINE_VERSION = 1


def machine_info():
    """Enough identity to tell whether a baseline transfers."""
    return {
        "system": platform.system(),
        "machine": platform.machine(),
        "processor": platform.processor() or platform.machine(),
        "cores": os.cpu_count() or 1,
        "python": platform.python_version(),
    }


def peak_rss_kb(child_pid):
    """ru_maxrss for a child, normalised to KiB (Linux reports KiB, macOS bytes)."""
    ru = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss
    # RUSAGE_CHILDREN is the max over *all* reaped children, so we use it only
    # as a monotonic signal; per-run deltas are computed by the caller from a
    # forked wrapper (see run_one).
    return ru


def run_one(binpath, svg, out, timeout):
    """Run the renderer once.  Returns (seconds, peak_rss_kb).

    Peak RSS comes from ``os.wait4`` so it is *this child's* high-water mark,
    not the maximum over every child ever reaped (which is what
    ``RUSAGE_CHILDREN`` reports and which never goes down).
    """
    try:
        p = subprocess.Popen([binpath, "-a", "2", svg, out],
                             stdout=subprocess.DEVNULL,
                             stderr=subprocess.DEVNULL)
    except OSError:
        return None, None
    t0 = time.perf_counter()
    try:
        _pid, status, ru = os.wait4(p.pid, 0)
    except ChildProcessError:
        return None, None
    dt = time.perf_counter() - t0
    # Keep Popen's bookkeeping consistent so __del__ does not warn.
    p.returncode = os.waitstatus_to_exitcode(status)
    if p.returncode != 0:
        return None, None
    # ru_maxrss units: KiB on Linux, bytes on macOS/BSD.
    unit = 1024.0 if platform.system() == "Linux" else 1.0
    return dt, ru.ru_maxrss * unit / 1024.0


def run_case(binpath, name, svg, repeat, timeout, outdir):
    times, rss = [], []
    for i in range(repeat):
        out = os.path.join(outdir, "%s_%d.png" % (name, i))
        dt, r = run_one(binpath, svg, out, timeout)
        if dt is None:
            return {"case": name, "status": "error", "runs": 0}
        times.append(dt)
        if r:
            rss.append(r)
    entry = {
        "case": name,
        "status": "ok",
        "runs": len(times),
        "best": round(min(times), 5),
        "median": round(statistics.median(times), 5),
        "worst": round(max(times), 5),
        "rss_kb": int(max(rss)) if rss else None,
    }
    return entry


def load_baseline():
    if not os.path.exists(BASELINE):
        return None
    try:
        return json.load(open(BASELINE))
    except (OSError, ValueError):
        return None


def comparable(baseline, machine):
    """True when the baseline was measured on a comparable machine."""
    if not baseline:
        return False
    if baseline.get("version") != BASELINE_VERSION:
        return False
    b = baseline.get("machine", {})
    # Same OS and architecture is the minimum for a meaningful comparison;
    # core count and CPU model are reported but not required to match exactly
    # because cloud VMs vary.
    return (b.get("system") == machine["system"] and
            b.get("machine") == machine["machine"])


def main(argv=None):
    p = argparse.ArgumentParser(description="svg2img benchmark")
    p.add_argument("--bin", default=os.path.join(ROOT, "svg2img"))
    p.add_argument("--repeat", type=int, default=5)
    p.add_argument("--threshold", type=float, default=1.35,
                   help="max slowdown vs baseline (default 1.35)")
    p.add_argument("--rss-threshold", type=float, default=1.75,
                   help="max RSS growth vs baseline (default 1.75)")
    p.add_argument("--timeout", type=float, default=120.0)
    p.add_argument("--json", default=DEFAULT_JSON)
    p.add_argument("--md", default="")
    p.add_argument("--filter", default="")
    p.add_argument("--update-baseline", action="store_true",
                   help="write baseline.json from this run")
    p.add_argument("--check", action="store_true",
                   help="exit non-zero on a regression")
    args = p.parse_args(argv)

    if not os.path.exists(args.bin):
        print("renderer not found: %s (run make)" % args.bin, file=sys.stderr)
        return 2
    if not os.path.isdir(CASES):
        print("no cases; run: python3 bench/gen.py", file=sys.stderr)
        return 2

    names = sorted(f for f in os.listdir(CASES) if f.endswith(".svg"))
    if args.filter:
        names = [n for n in names if args.filter in n]
    if not names:
        print("no cases matched", file=sys.stderr)
        return 2

    tmp = tempfile.mkdtemp(prefix="svg2img_bench_")
    t0 = time.time()
    results = []
    for name in names:
        stem = name[:-4]
        r = run_case(args.bin, stem, os.path.join(CASES, name),
                     args.repeat, args.timeout, tmp)
        r["name"] = stem
        results.append(r)
        if r["status"] == "ok":
            rss = ("%.1f MB" % (r["rss_kb"] / 1024.0)) if r["rss_kb"] else "n/a"
            print("  %-16s best %7.1f ms  median %7.1f ms  rss %s"
                  % (stem, r["best"] * 1000, r["median"] * 1000, rss))
        else:
            print("  %-16s ERROR (timeout or non-zero exit)" % stem)
    total = time.time() - t0

    machine = machine_info()
    baseline = load_baseline()
    base_ok = comparable(baseline, machine)
    base = {c["case"]: c for c in baseline.get("cases", [])} if base_ok else {}

    regressions = []
    for r in results:
        r["speedup_vs_baseline"] = None
        r["rss_growth"] = None
        if r["status"] != "ok":
            continue
        b = base.get(r["name"])
        if not b or not b.get("best"):
            continue
        ratio = r["best"] / b["best"]
        r["baseline_best"] = b["best"]
        r["speedup_vs_baseline"] = round(ratio, 4)
        if ratio > args.threshold:
            regressions.append((r["name"], "time", ratio, args.threshold))
        if b.get("rss_kb") and r.get("rss_kb"):
            growth = r["rss_kb"] / float(b["rss_kb"])
            r["rss_growth"] = round(growth, 4)
            if growth > args.rss_threshold:
                regressions.append((r["name"], "rss", growth, args.rss_threshold))

    summary = {
        "version": BASELINE_VERSION,
        "generated": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "machine": machine,
        "bin": os.path.relpath(args.bin, ROOT),
        "repeat": args.repeat,
        "threshold": args.threshold,
        "rss_threshold": args.rss_threshold,
        "seconds": round(total, 2),
        "baselined": base_ok,
        "baseline_machine": baseline.get("machine") if baseline else None,
        "cases": results,
        "regressions": [{"case": n, "metric": m, "ratio": round(v, 4),
                         "limit": lim} for n, m, v, lim in regressions],
    }

    if args.update_baseline:
        out = {"version": BASELINE_VERSION,
               "machine": machine,
               "bin": os.path.relpath(args.bin, ROOT),
               "repeat": args.repeat,
               "cases": [{"case": r["name"], "best": r.get("best"),
                          "median": r.get("median"), "rss_kb": r.get("rss_kb")}
                         for r in results if r["status"] == "ok"]}
        with open(BASELINE, "w") as f:
            json.dump(out, f, indent=2, sort_keys=True)
            f.write("\n")
        print("baseline: %s" % BASELINE)

    with open(args.json, "w") as f:
        json.dump(summary, f, indent=2, sort_keys=True)
        f.write("\n")
    print("\n%d cases, repeat %d, %.1fs total (best-of-N)"
          % (len(results), args.repeat, total))
    if not base_ok:
        print("no comparable baseline (%s); reporting only"
              % (baseline.get("machine") if baseline else "none"))
    elif regressions:
        print("regressions:")
        for n, m, v, lim in regressions:
            print("  %-16s %s %.2fx > %.2fx" % (n, m, v, lim))
    else:
        print("no regression over threshold %.2fx" % args.threshold)
    print("summary: %s" % args.json)
    if args.md:
        with open(args.md, "w") as f:
            f.write(markdown(summary))
        print("report: %s" % args.md)
    if args.check and regressions:
        return 1
    return 0


def markdown(s):
    lines = ["# svg2img benchmark", "",
             "Machine: %s %s, %d cores, Python %s  " % (
                 s["machine"]["system"], s["machine"]["machine"],
                 s["machine"]["cores"], s["machine"]["python"]),
             "Renderer: `%s`, repeat %d (best-of-N), %.1fs total  " % (
                 s["bin"], s["repeat"], s["seconds"]),
             "Baseline: %s" % ("comparable" if s["baselined"] else
                               "none / not comparable"),
             "",
             "| case | best ms | median ms | RSS MB | vs baseline |",
             "|---|---|---|---|---|"]
    for r in s["cases"]:
        if r["status"] != "ok":
            lines.append("| %s | ERROR | | | |" % r["name"])
            continue
        lines.append("| %s | %.1f | %.1f | %s | %s |" % (
            r["name"], r["best"] * 1000, r["median"] * 1000,
            "%.1f" % (r["rss_kb"] / 1024.0) if r.get("rss_kb") else "n/a",
            "%.2fx" % r["speedup_vs_baseline"]
            if r.get("speedup_vs_baseline") else "-"))
    lines += ["", "## Regressions", ""]
    if not s["regressions"]:
        lines.append("none")
    for r in s["regressions"]:
        lines.append("- %s: %s %.2fx over limit %.2fx" % (
            r["case"], r["metric"], r["ratio"], r["limit"]))
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    sys.exit(main())